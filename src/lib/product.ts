/**
 * Демо-карточки, которыми наполнен каталог до первой выгрузки из 1С.
 * Их onec_id начинается с «demo-» — такой GUID 1С не выдаёт никогда,
 * поэтому реальный товар под это правило не попадёт, а первая же
 * настоящая выгрузка вытеснит демо-позиции (владелец удаляет их в админке).
 *
 * На сайте такие карточки помечаются явно: обещать наличие того, чего
 * в магазине нет, нельзя даже ради красивой сетки каталога.
 */
export function isDemoProduct(product: { onec_id: string | null }): boolean {
  return Boolean(product.onec_id?.startsWith("demo-"));
}
